"""Regression tests for Python bytecode leaking into the phase delta.

Phase 1 escalated with UNREVIEWABLE_DELTA listing `__pycache__/*.pyc` under src/ and
migrations/. An earlier fix had already set PYTHONDONTWRITEBYTECODE=1 — but only on the
*gate* command. The audit log proves the bytecode was written between
`operation_started phase-1:implement:1` and `operation_completed`, i.e. by the implementer
subprocess, whose environment was built by `sanitized_environment` with no such variable.

Suppression now covers every role the supervisor launches into a workspace, and a narrow
fail-closed purge runs immediately before the delta is constructed. Everything that is not
generated bytecode must still reach review, and must still escalate when unreviewable.
"""
import json
import os
import subprocess
import tempfile
import unittest
from pathlib import Path
from types import SimpleNamespace

from buildctl.supervisor.agents import RoleRunner, host_auth_environment
from buildctl.supervisor.gates import MechanicalGates
from buildctl.supervisor.git import GitManager, GitSafetyError
from buildctl.supervisor.isolation import FakeIsolationBackend, IsolationContext, sanitized_environment
from buildctl.supervisor.safety import UnsafeCleanup, purge_ephemeral_artifacts, suppress_ephemeral_artifacts

ALLOWED = ("src/", "migrations/", "tests/product/", "pyproject.toml")


def make_workspace(root: Path) -> Path:
    workspace = root / "ws"
    for relative in ("src/relay", "migrations/versions", "tests/product"):
        (workspace / relative).mkdir(parents=True, exist_ok=True)
    return workspace


def write_bytecode(workspace: Path, *relatives: str) -> None:
    for relative in relatives:
        target = workspace / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(b"\xcf\x0d\x0d\x0a\x00\x00\x00\x00bytecode")


class SuppressionCoversEveryRoleTests(unittest.TestCase):
    """G: the shared mechanism is reused, not overridden by env construction."""

    def test_the_helper_sets_the_variable(self):
        self.assertEqual(suppress_ephemeral_artifacts({})["PYTHONDONTWRITEBYTECODE"], "1")

    def test_the_helper_preserves_the_environment_it_wraps(self):
        base = sanitized_environment("implementer", {"TOKEN": "x"})
        wrapped = suppress_ephemeral_artifacts(dict(base))
        for key, value in base.items():
            self.assertEqual(wrapped[key], value, f"{key} was lost")
        self.assertEqual(wrapped["PYTHONDONTWRITEBYTECODE"], "1")

    def test_the_host_authenticated_reviewer_environment_is_covered(self):
        self.assertEqual(suppress_ephemeral_artifacts(host_auth_environment("reviewer"))["PYTHONDONTWRITEBYTECODE"], "1")

    def test_the_implementer_subprocess_receives_the_variable(self):
        """The actual gap: this is the process that wrote the bytecode."""
        captured: list = []
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory).resolve()
            workspace, control, repo = root / "ws", root / "ctl", root / "repo"
            for path in (workspace, control, repo):
                path.mkdir(parents=True)

            def runner(argv, **kwargs):
                captured.append(kwargs["env"])
                out = Path(argv[argv.index("--out") + 1])
                out.parent.mkdir(parents=True, exist_ok=True)
                out.write_text(json.dumps({"status": "complete"}))
                return subprocess.CompletedProcess(argv, 0, "", "")

            config = {"roles": {"implementer": {"auth_mode": "none", "credential_env": [],
                                                "network": False,
                                                "command": ["/bin/echo", "--out", "{output}"]}},
                      "_trusted_executables": {}}
            context = IsolationContext("implementer", workspace, control, repo, host_home=root)
            RoleRunner(config, FakeIsolationBackend(), context, runner).run(
                "implementer", "prompt", control / "PHASE_RESULT.json", 30)
        self.assertEqual(captured[0]["PYTHONDONTWRITEBYTECODE"], "1")

    def test_the_gate_subprocess_still_receives_the_variable(self):
        """H: the previous dependency-provisioning fix stays intact."""
        seen: list = []
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory).resolve()
            workspace, control, repo = root / "ws", root / "ctl", root / "repo"
            for path in (workspace, control, repo):
                path.mkdir(parents=True)
            (workspace / "pyproject.toml").write_text('[project]\nname="p"\nversion="0"\ndependencies=[]\n')

            def runner(command, **kwargs):
                command = list(command)
                if command[1:3] == ["-m", "venv"]:
                    venv = Path(command[3]); (venv / "bin").mkdir(parents=True, exist_ok=True)
                    (venv / "bin" / "python").write_text("#!/bin/sh\n")
                    (venv / "lib" / "python3.12" / "site-packages").mkdir(parents=True, exist_ok=True)
                else:
                    seen.append(kwargs.get("env", {}))
                return subprocess.CompletedProcess(command, 0, "", "")

            phase = SimpleNamespace(required_files=(),
                                    commands=(("{python}", "-m", "unittest", "discover"),))
            result = MechanicalGates(workspace, control, repo, FakeIsolationBackend(), runner).run(phase, 30)
        self.assertTrue(result.passed, "dependency provisioning must still work")
        self.assertEqual(seen[0]["PYTHONDONTWRITEBYTECODE"], "1")


class RealInterpreterLeavesNoBytecodeTests(unittest.TestCase):
    """A: execution through the corrected environment leaves the workspace clean."""

    def test_importing_a_module_under_the_suppressed_environment_writes_nothing(self):
        with tempfile.TemporaryDirectory() as directory:
            workspace = make_workspace(Path(directory).resolve())
            package = workspace / "src" / "relay"
            (package / "__init__.py").write_text("VALUE = 1\n")
            (package / "domain.py").write_text("from relay import VALUE\n")
            env = suppress_ephemeral_artifacts(sanitized_environment("implementer"))
            env["PYTHONPATH"] = str(workspace / "src")
            completed = subprocess.run([os.sys.executable, "-c", "import relay.domain"],
                                       cwd=str(workspace), env=env, text=True, capture_output=True)
            self.assertEqual(completed.returncode, 0, completed.stderr)
            self.assertEqual(list(workspace.rglob("__pycache__")), [])
            self.assertEqual(list(workspace.rglob("*.pyc")), [])

    def test_without_suppression_the_same_import_does_write_bytecode(self):
        """Proves the test above is actually measuring the variable's effect."""
        with tempfile.TemporaryDirectory() as directory:
            workspace = make_workspace(Path(directory).resolve())
            package = workspace / "src" / "relay"
            (package / "__init__.py").write_text("VALUE = 1\n")
            (package / "domain.py").write_text("from relay import VALUE\n")
            env = sanitized_environment("implementer")
            env["PYTHONPATH"] = str(workspace / "src")
            env.pop("PYTHONDONTWRITEBYTECODE", None)
            subprocess.run([os.sys.executable, "-c", "import relay.domain"],
                           cwd=str(workspace), env=env, text=True, capture_output=True)
            self.assertTrue(list(workspace.rglob("*.pyc")), "expected the unsuppressed run to leave bytecode")


class PurgeRemovesGeneratedBytecodeTests(unittest.TestCase):
    """B: the exact paths from the escalation are cleaned."""

    def test_the_escalated_paths_are_removed(self):
        with tempfile.TemporaryDirectory() as directory:
            workspace = make_workspace(Path(directory).resolve())
            write_bytecode(workspace,
                           "migrations/__pycache__/env.cpython-313.pyc",
                           "migrations/versions/__pycache__/0001_foundation.cpython-313.pyc",
                           "src/relay/__pycache__/app.cpython-313.pyc",
                           "src/relay/__pycache__/domain.cpython-313.pyc")
            removed = purge_ephemeral_artifacts(workspace)
            self.assertEqual(list(workspace.rglob("*.pyc")), [])
            self.assertEqual(list(workspace.rglob("__pycache__")), [])
            self.assertIn("migrations/__pycache__/env.cpython-313.pyc", removed)
            self.assertIn("src/relay/__pycache__/app.cpython-313.pyc", removed)

    def test_optimised_bytecode_and_loose_files_are_removed(self):
        with tempfile.TemporaryDirectory() as directory:
            workspace = make_workspace(Path(directory).resolve())
            write_bytecode(workspace, "src/relay/__pycache__/db.cpython-313.pyo",
                           "src/legacy.pyc")
            purge_ephemeral_artifacts(workspace)
            self.assertEqual(list(workspace.rglob("*.py[co]")), [])

    def test_a_clean_workspace_is_left_alone(self):
        with tempfile.TemporaryDirectory() as directory:
            workspace = make_workspace(Path(directory).resolve())
            (workspace / "src" / "relay" / "app.py").write_text("x = 1\n")
            self.assertEqual(purge_ephemeral_artifacts(workspace), ())
            self.assertTrue((workspace / "src" / "relay" / "app.py").is_file())

    def test_the_agent_runtime_and_git_directory_are_never_traversed(self):
        with tempfile.TemporaryDirectory() as directory:
            workspace = make_workspace(Path(directory).resolve())
            write_bytecode(workspace, ".factory-runtime/op/__pycache__/staged.cpython-313.pyc",
                           ".git/hooks/__pycache__/hook.cpython-313.pyc")
            purge_ephemeral_artifacts(workspace)
            self.assertTrue((workspace / ".factory-runtime/op/__pycache__/staged.cpython-313.pyc").is_file())
            self.assertTrue((workspace / ".git/hooks/__pycache__/hook.cpython-313.pyc").is_file())


class PurgeLeavesEverythingElseAloneTests(unittest.TestCase):
    """C and D: source, untracked files and binaries survive."""

    def test_source_and_untracked_files_survive(self):
        with tempfile.TemporaryDirectory() as directory:
            workspace = make_workspace(Path(directory).resolve())
            files = {"src/relay/app.py": "app\n",
                     "src/relay/notes.txt": "notes\n",
                     "scratch_untracked.md": "scratch\n",
                     "tests/product/test_foundation.py": "test\n"}
            for relative, text in files.items():
                target = workspace / relative
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(text)
            write_bytecode(workspace, "src/relay/__pycache__/app.cpython-313.pyc")
            purge_ephemeral_artifacts(workspace)
            for relative, text in files.items():
                self.assertEqual((workspace / relative).read_text(), text, relative)

    def test_arbitrary_binaries_are_not_removed(self):
        with tempfile.TemporaryDirectory() as directory:
            workspace = make_workspace(Path(directory).resolve())
            binary = workspace / "src" / "relay" / "unexpected.bin"
            binary.write_bytes(b"\x00\x01\x02\x03")
            purge_ephemeral_artifacts(workspace)
            self.assertTrue(binary.is_file(), "cleanup must not touch arbitrary binaries")

    def test_a_pycache_holding_non_bytecode_fails_rather_than_deleting(self):
        """Fail closed: never let cleanup be a way to make source disappear."""
        with tempfile.TemporaryDirectory() as directory:
            workspace = make_workspace(Path(directory).resolve())
            cache = workspace / "src" / "relay" / "__pycache__"
            cache.mkdir(parents=True)
            (cache / "app.cpython-313.pyc").write_bytes(b"\x00")
            (cache / "smuggled.py").write_text("print('hidden source')\n")
            with self.assertRaises(UnsafeCleanup):
                purge_ephemeral_artifacts(workspace)
            self.assertTrue((cache / "smuggled.py").is_file())
            self.assertTrue((cache / "app.cpython-313.pyc").is_file())


class PurgeCannotEscapeTheWorkspaceTests(unittest.TestCase):
    """F: no traversal out of the disposable workspace, by any route."""

    def test_a_symlinked_pycache_directory_is_not_followed(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory).resolve()
            workspace = make_workspace(root)
            outside = root / "outside" / "__pycache__"
            outside.mkdir(parents=True)
            victim = outside / "host.cpython-313.pyc"
            victim.write_bytes(b"\x00")
            (workspace / "src" / "relay" / "__pycache__").symlink_to(outside)
            purge_ephemeral_artifacts(workspace)
            self.assertTrue(victim.is_file(), "cleanup followed a symlink out of the workspace")

    def test_a_symlinked_directory_containing_bytecode_is_not_followed(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory).resolve()
            workspace = make_workspace(root)
            outside = root / "hostlib"
            (outside / "__pycache__").mkdir(parents=True)
            victim = outside / "__pycache__" / "host.cpython-313.pyc"
            victim.write_bytes(b"\x00")
            (workspace / "src" / "linked").symlink_to(outside)
            purge_ephemeral_artifacts(workspace)
            self.assertTrue(victim.is_file())

    def test_a_symlinked_bytecode_file_is_refused(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory).resolve()
            workspace = make_workspace(root)
            victim = root / "host.pyc"
            victim.write_bytes(b"\x00")
            (workspace / "src" / "escape.pyc").symlink_to(victim)
            with self.assertRaises(UnsafeCleanup):
                purge_ephemeral_artifacts(workspace)
            self.assertTrue(victim.is_file())

    def test_a_missing_workspace_raises_rather_than_walking_anything(self):
        with tempfile.TemporaryDirectory() as directory:
            with self.assertRaises(OSError):
                purge_ephemeral_artifacts(Path(directory) / "does-not-exist")


class DeltaIntegrationTests(unittest.TestCase):
    """The end-to-end contract: bytecode never reaches review, everything else still does."""

    def _repo(self, root: Path) -> GitManager:
        return GitManager(root, {"git": {"push": False, "create_pr": False, "merge": False}})

    def test_bytecode_never_enters_the_attributed_delta(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory).resolve()
            workspace = make_workspace(root)
            (workspace / "src" / "relay" / "app.py").write_text("x = 1\n")
            baseline = self._repo(root).manifest(workspace)
            write_bytecode(workspace,
                           "src/relay/__pycache__/app.cpython-313.pyc",
                           "migrations/__pycache__/env.cpython-313.pyc")
            (workspace / "src" / "relay" / "domain.py").write_text("y = 2\n")
            delta = self._repo(root).attributed_delta(workspace, baseline, ALLOWED)
            self.assertIn("src/relay/domain.py", delta.added_or_modified)
            self.assertFalse([p for p in delta.added_or_modified if p.endswith(".pyc")],
                             "bytecode reached the delta")

    def test_review_evidence_has_nothing_unreviewable_after_cleanup(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory).resolve()
            workspace = make_workspace(root)
            baseline = self._repo(root).manifest(workspace)
            (workspace / "src" / "relay" / "app.py").write_text("x = 1\n")
            write_bytecode(workspace, "src/relay/__pycache__/app.cpython-313.pyc")
            delta = self._repo(root).attributed_delta(workspace, baseline, ALLOWED)
            evidence = self._repo(root).review_evidence(workspace, delta, {"passed": True})
            self.assertEqual(evidence["unreviewable"], [])

    def test_an_unexpected_binary_still_produces_an_unreviewable_delta(self):
        """E: the protection this fix must not weaken."""
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory).resolve()
            workspace = make_workspace(root)
            baseline = self._repo(root).manifest(workspace)
            (workspace / "src" / "relay" / "unexpected.bin").write_bytes(bytes(range(256)))
            delta = self._repo(root).attributed_delta(workspace, baseline, ALLOWED)
            evidence = self._repo(root).review_evidence(workspace, delta, {"passed": True})
            self.assertEqual(evidence["unreviewable"], ["src/relay/unexpected.bin"])

    def test_unattributed_paths_are_still_refused(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory).resolve()
            workspace = make_workspace(root)
            baseline = self._repo(root).manifest(workspace)
            (workspace / "elsewhere.py").write_text("x = 1\n")
            with self.assertRaisesRegex(GitSafetyError, "unattributed path"):
                self._repo(root).attributed_delta(workspace, baseline, ALLOWED)

    def test_unsafe_cleanup_fails_the_delta_rather_than_proceeding(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory).resolve()
            workspace = make_workspace(root)
            baseline = self._repo(root).manifest(workspace)
            cache = workspace / "src" / "relay" / "__pycache__"
            cache.mkdir(parents=True)
            (cache / "smuggled.py").write_text("hidden\n")
            with self.assertRaisesRegex(GitSafetyError, "artifact cleanup failed"):
                self._repo(root).attributed_delta(workspace, baseline, ALLOWED)
